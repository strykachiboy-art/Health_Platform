// Fixed, compile-time endpoint and projection catalog, reviewed against the
// pinned Flask schemas. No arbitrary endpoint, body key, actor, token, tenant
// or session-clinic input. Clinic registry identifiers are resource IDs only.
class SaAdminAnchor {
  const SaAdminAnchor(
    this.path,
    this.shape,
    this.keys,
    this.scope, {
    this.match = const {},
    this.skip = '',
    this.state = const {},
    this.select = false,
  });
  final String path, shape, scope, skip;
  final List<String> keys;
  final Map<String, String> match;
  final Map<String, List<Object?>> state;
  final bool select;
}

class SaAdminSpec {
  const SaAdminSpec(
    this.title,
    this.group,
    this.verb,
    this.path,
    this.shape,
    this.keys,
    this.scope,
    this.fields, {
    this.match = const {},
    this.anchors = const [],
    this.echo = const [],
    this.expected = const {},
    this.omit = const [],
    this.staging = false,
    this.selected = false,
    this.createKey = const [],
    this.decimal = const [],
    this.nonempty = false,
  });
  final String title, group, verb, path, shape, scope;
  final List<String> keys, echo, omit, createKey, decimal;
  final List<SaField> fields;
  final Map<String, String> match;
  final Map<String, Object?> expected;
  final List<SaAdminAnchor> anchors;
  final bool staging, selected, nonempty;

  static final _parameter = RegExp(r'\{([a-z_]+)\}');
  static String render(String template, Map<String, dynamic> values) {
    return template.replaceAllMapped(_parameter, (m) {
      final k = m.group(1)!;
      final v = values[k];
      if (v is int && v > 0 && v <= 2147483647) {
        return v.toString();
      }
      if (k == 'provider' &&
          v is String &&
          RegExp(r'^[A-Za-z0-9][A-Za-z0-9_-]{0,79}$').hasMatch(v)) {
        return Uri.encodeComponent(v);
      }
      throw const FormatException('Invalid resource identifier.');
    });
  }

  SaRequest prepare(SaOperation op, Map<String, dynamic> values) {
    // Only schema-owned fields were decoded by the original shared form parser.
    // A clinic registry record ID is not an authorization or context override.
    if (fields.any((f) => f.key == 'lookup_page')) {
      values['lookup_page'] ??= 1;
    }
    for (final key in decimal) {
      final value = values[key];
      if (value != null &&
          (value is! String ||
              !RegExp(r'^\d{1,12}(?:\.\d{1,2})?$').hasMatch(value))) {
        throw const FormatException(
          'Use a non-negative decimal, at most two decimal places.',
        );
      }
    }
    if (op == SaOperation.adminStockMovement) {
      final raw = values['quantity'];
      if (raw is! String || !RegExp(r'^-?[1-9]\d{0,9}$').hasMatch(raw)) {
        throw const FormatException('Enter a nonzero whole quantity.');
      }
      final quantity = int.parse(raw);
      if (quantity.abs() > 2147483647 ||
          (quantity < 0 && values['movement_type'] != 'adjustment')) {
        throw const FormatException('Invalid stock quantity.');
      }
      values['quantity'] = quantity;
    }
    if (values['coverage_start'] is String &&
        values['coverage_end'] is String &&
        (values['coverage_end'] as String).compareTo(
              values['coverage_start'] as String,
            ) <
            0) {
      throw const FormatException('Coverage end precedes start.');
    }
    final body = Map<String, dynamic>.of(values);
    for (final m in _parameter.allMatches(path)) {
      body.remove(m.group(1));
    }
    for (final key in omit) {
      body.remove(key);
    }
    final target = render(path, values);
    if (nonempty && body.isEmpty) {
      throw const FormatException('Enter at least one administrative change.');
    }
    final suffix = verb == 'GET' && body.isNotEmpty
        ? '?${Uri(queryParameters: {for (final e in body.entries) e.key: e.value.toString()}).query}'
        : '';
    return SaRequest._(
      op,
      'api/v1/$target$suffix',
      _freezeMap(values),
      _freezeMap(verb == 'GET' ? <String, dynamic>{} : body),
    );
  }
}

